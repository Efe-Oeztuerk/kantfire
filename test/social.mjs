import { register, connect } from './client.js';
const base = 'http://localhost:3999';
const call = (tok, path, body) => fetch(base + '/api' + path, { method: body ? 'POST' : 'GET', headers: { 'Content-Type': 'application/json', Authorization: 'Bearer ' + tok }, body: body ? JSON.stringify(body) : undefined }).then((r) => r.json());
const ta = await register(base, 'soc_anna'), tb = await register(base, 'soc_ben');
const A = await connect(base, ta), B = await connect(base, tb);
console.log('Anfrage:', JSON.stringify(await call(ta, '/friends/request', { name: 'soc_ben' })));
await new Promise((r) => setTimeout(r, 200));
console.log('Ben bekommt Live-Benachrichtigung:', B.msgs.some((m) => m.t === 'friendRequest'));
const meB = await call(tb, '/me');
console.log('Annehmen:', JSON.stringify(await call(tb, '/friends/accept', { id: meB.requests[0].id })));
const meA = await call(ta, '/me');
console.log('Anna Freunde:', meA.friends.map((f) => `${f.name} (${f.status})`).join(', '));
A.send({ t: 'create', private: true, mode: 'comp2', bots: true });
await new Promise((r) => setTimeout(r, 400));
A.send({ t: 'invite', to: meB.id });
await new Promise((r) => setTimeout(r, 300));
const inv = B.msgs.find((m) => m.t === 'invite');
console.log('Einladung bei Ben:', inv && `${inv.from} -> Raum ${inv.room}`);
B.send({ t: 'join', id: inv.room });
await new Promise((r) => setTimeout(r, 400));
console.log('Ben im selben Raum:', B.last.welcome?.room.id === A.last.welcome.room.id);
console.log('Server-Browser (öffentlich):', (await call(ta, '/servers')).rooms.length, 'Räume; private Lobby versteckt:', !(await call(ta, '/servers')).rooms.some((r) => r.id === inv.room));
console.log('Rangliste:', JSON.stringify(await call(ta, '/leaderboard?mode=comp5')).slice(0, 80));
console.log('Blockieren:', JSON.stringify(await call(ta, '/block', { id: meB.id })));
process.exit(0);
